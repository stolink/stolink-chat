async def main():
    print("\n🔄 데모 데이터 임베딩 생성 및 삽입 중...")
    
    # PostgreSQL 직접 연결
    DB_HOST = os.getenv("POSTGRES_HOST", "host.docker.internal")
    DB_PORT = int(os.getenv("POSTGRES_PORT", 5432))
    DB_USER = os.getenv("POSTGRES_USER", "stolink")
    DB_PASSWORD = os.getenv("POSTGRES_PASSWORD", "stolink123")
    DB_NAME = os.getenv("POSTGRES_DB", "stolink")
    
    conn = await asyncpg.connect(
        host=DB_HOST,
        port=DB_PORT,
        user=DB_USER,
        password=DB_PASSWORD,
        database=DB_NAME
    )
    
    document_id = "00000000-0000-0000-0000-000000000002"
    
    for idx, (seq_order, nav_title, content) in enumerate(demo_sections, 1):
        print(f"  [{idx}/{len(demo_sections)}] {nav_title} - 임베딩 생성 중... ({len(content):,}자)")
        
        # Gemini 임베딩 생성
        embedding = embedding_service.get_embedding(content)
        
        # PostgreSQL vector 형식으로 변환
        embedding_str = f"[{','.join(map(str, embedding))}]"
        
        # PostgreSQL 삽입
        await conn.execute("""
            INSERT INTO sections (document_id, sequence_order, nav_title, content, embedding)
            VALUES ($1::uuid, $2, $3, $4, $5::vector)
        """, document_id, seq_order, nav_title, content, embedding_str)
        
        print(f"  ✅ 완료")
    
    await conn.close()
    
    total_chars = sum(len(content) for _, _, content in demo_sections)
    print(f"\n✅ 데모 데이터 삽입 완료!")
    print(f"   총 {len(demo_sections)}개 섹션 추가")
    print(f"   총 글자 수: {total_chars:,}자")

if __name__ == "__main__":
    asyncio.run(main())
